import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { AccountPreferenceStore, normalizePreferences } from '../src/account/preferences.ts';
import type { AccountUser } from '../src/account/types.ts';
const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); }, removeItem: (key: string) => { values.delete(key); } };
const saves: unknown[] = [];
const store = new AccountPreferenceStore(async (id, value) => { saves.push({ id, value }); }, storage);
assert.equal(store.laboratoryMode, 'full');
store.setLaboratoryMode('lite'); await store.flush();
assert.equal(saves.length, 0, 'Guest preference never sends an account request');
const restored = new AccountPreferenceStore(async () => {}, storage);
assert.equal(restored.laboratoryMode, 'lite', 'Guest mode survives reload');
const user = (id: string): AccountUser => ({ id, email: id, displayName: id, role: 'student', class: null });
store.activate(user('one'));
assert.equal(store.laboratoryMode, 'full', 'Old accounts default to full independently of the guest');
store.setLaboratoryMode('lite'); await store.flush();
assert.deepEqual(saves, [{ id: 'one', value: { laboratoryMode: 'lite' } }]);
store.activate(user('two')); assert.equal(store.laboratoryMode, 'full', 'Account modes are isolated');
store.activate(null); assert.equal(store.laboratoryMode, 'lite', 'Logout restores the independent guest setting');
assert.deepEqual(normalizePreferences({ laboratoryMode: 'bad' }), {});
assert.deepEqual(normalizePreferences({ laboratoryMode: true }), {});
assert.deepEqual(normalizePreferences({ laboratoryMode: 'lite' }), { laboratoryMode: 'lite' });
const engine = readFileSync(new URL('../src/core/Engine.ts', import.meta.url), 'utf8');
const baseInitialization = engine.slice(engine.indexOf('  private initWorld()'), engine.indexOf('  public async prepareLaboratory()'));
assert(!engine.slice(engine.indexOf('  constructor('), engine.indexOf('  private initRenderer(')).includes('new MoleculeHologramStage('), 'Molecular renderer is lazy as well');
assert(!baseInitialization.includes('new Laboratory('));
assert(!baseInitialization.includes('new HoloTable('));
assert(!baseInitialization.includes('new BeakerMesh('));
assert(!baseInitialization.includes('initImageBasedLighting('));
assert(!baseInitialization.includes('bakeAllTexturesAsync('));
assert(engine.includes('new HologramStage(false)'), 'Lite startup does not allocate decorative particles');
console.log('✓ Laboratory modes: guest persistence, account isolation, validation & lazy initialization');
